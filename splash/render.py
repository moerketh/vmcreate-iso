#!/usr/bin/env python3
"""Render the VMCreate Plymouth theme graphics.

The PNGs under splash/vmcreate/ are generated by this script and committed,
so the ISO build needs no Python or Pillow. Re-run after changing the glyphs
or the palette:

    python3 splash/render.py            # writes splash/vmcreate/**/*.png
    python3 splash/render.py --preview  # also writes splash/preview.png

The wordmark is hand-drawn pixel art (no font, no licensing questions):
each glyph is a grid of blocks, scaled up, with a drop shadow, a vertical
colour gradient, CRT-style scanlines and a soft glow. Assets come in two
palettes (blue default, red easter egg); single-letter sprites in
letters/ and letters_red/ back the flip and rain effects in vmcreate.script.
"""

import argparse
import os

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "vmcreate")

# Palettes — Tokyo Night-ish, matching the dark/flat Omarchy look.
# "red" is the easter-egg palette (any key at the console cycles to it).
SHADOW = (0x2A, 0x2E, 0x45)
SHADOW_RED = (0x45, 0x22, 0x2C)

PALETTES = {
    "blue": {
        "suffix": "",
        "letters_dir": "letters",
        "shadow": SHADOW,
        "bg_top": (0x16, 0x16, 0x1E),
        "bg_bottom": (0x1A, 0x1B, 0x26),
        "vm": ((0x7D, 0xCF, 0xFF), (0x7A, 0xA2, 0xF7)),    # cyan → blue
        "cr": ((0xE0, 0xE6, 0xFF), (0xA9, 0xB1, 0xD6)),    # near-white → grey-blue
        "glow": (0x7A, 0xA2, 0xF7),
        "track": (0x29, 0x2E, 0x42),
        "bar": ((0x7D, 0xCF, 0xFF), (0xBB, 0x9A, 0xF7)),   # cyan → purple
        "cursor": (0x7D, 0xCF, 0xFF),
        "message": (0xA9, 0xB1, 0xD6),
        "version": (0x56, 0x5F, 0x89),
    },
    "red": {
        "suffix": "_red",
        "letters_dir": "letters_red",
        "shadow": SHADOW_RED,
        "bg_top": (0x1F, 0x12, 0x16),
        "bg_bottom": (0x27, 0x15, 0x1C),
        "vm": ((0xFF, 0x9E, 0xB4), (0xF7, 0x76, 0x8E)),    # pink → red
        "cr": ((0xF2, 0xD5, 0xDC), (0xD4, 0x7A, 0x92)),    # rose → crimson
        "glow": (0xF7, 0x76, 0x8E),
        "track": (0x3A, 0x22, 0x28),
        "bar": ((0xFF, 0x9E, 0xB4), (0xF7, 0x76, 0x8E)),
        "cursor": (0xF7, 0x76, 0x8E),
        "message": (0xE0, 0xAF, 0xBA),
        "version": (0x8C, 0x59, 0x6B),
    },
}

BLOCK = 10          # px per glyph block
LETTER_GAP = 1      # blocks between letters
WORD_GAP = 3        # blocks between "VM" and "CREATE"
SHADOW_OFFSET = 5   # px, down-right
GLOW_RADIUS = 14
PAD = 24            # transparent margin so the glow isn't clipped

GLYPHS = {
    "V": ["##...##", "##...##", "##...##", "##...##", "##...##", "##...##",
          ".##.##.", ".##.##.", "..###..", "..###..", "..###.."],
    "M": ["##...##", "###.###", "#######", "##.#.##", "##...##", "##...##",
          "##...##", "##...##", "##...##", "##...##", "##...##"],
    "C": [".######", "#######", "##.....", "##.....", "##.....", "##.....",
          "##.....", "##.....", "##.....", "#######", ".######"],
    "R": ["######.", "#######", "##...##", "##...##", "##...##", "#######",
          "######.", "##..##.", "##...##", "##...##", "##...##"],
    "E": ["#######", "#######", "##.....", "##.....", "##.....", "######.",
          "######.", "##.....", "##.....", "#######", "#######"],
    "A": [".#####.", "#######", "##...##", "##...##", "##...##", "#######",
          "#######", "##...##", "##...##", "##...##", "##...##"],
    "T": ["######", "######", "..##..", "..##..", "..##..", "..##..",
          "..##..", "..##..", "..##..", "..##..", "..##.."],
}
ROWS = 11


def lerp(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def word_offsets():
    """(letter, block offset) for each glyph in the wordmark, in order."""
    letters = []
    x = 0
    for c in "VM":
        letters.append((c, x))
        x += len(GLYPHS[c][0]) + LETTER_GAP
    x += WORD_GAP - LETTER_GAP
    for c in "CREATE":
        letters.append((c, x))
        x += len(GLYPHS[c][0]) + LETTER_GAP
    return letters


def word_mask(word):
    """1-bit-ish L mask of a word drawn in blocks; returns (mask, width_px)."""
    cols = sum(len(GLYPHS[c][0]) for c in word) + LETTER_GAP * (len(word) - 1)
    mask = Image.new("L", (cols * BLOCK, ROWS * BLOCK), 0)
    d = ImageDraw.Draw(mask)
    x0 = 0
    for c in word:
        g = GLYPHS[c]
        for r, row in enumerate(g):
            for col, ch in enumerate(row):
                if ch == "#":
                    x, y = (x0 + col) * BLOCK, r * BLOCK
                    d.rectangle([x, y, x + BLOCK - 1, y + BLOCK - 1], fill=255)
        x0 += len(g[0]) + LETTER_GAP
    return mask


def vertical_gradient(size, top, bottom):
    w, h = size
    img = Image.new("RGB", size)
    d = ImageDraw.Draw(img)
    for y in range(h):
        d.line([(0, y), (w, y)], fill=lerp(top, bottom, y / max(1, h - 1)))
    return img


def horizontal_gradient(size, left, right):
    w, h = size
    img = Image.new("RGB", size)
    d = ImageDraw.Draw(img)
    for x in range(w):
        d.line([(x, 0), (x, h)], fill=lerp(left, right, x / max(1, w - 1)))
    return img


def scanlines(mask):
    """Darken every third pixel row inside the letters (CRT look)."""
    lines = Image.new("L", mask.size, 255)
    d = ImageDraw.Draw(lines)
    for y in range(2, mask.size[1], 3):
        d.line([(0, y), (mask.size[0], y)], fill=200)
    return lines


def render_glyph(mask, width_px, fill, p, pos, full):
    """A glyph composited with glow, drop shadow and colour fill.

    The canvas carries a transparent margin so the glow isn't clipped. The
    wordmark keeps its original margins (glyph at PAD); single letters use
    symmetric margins (PAD + SHADOW_OFFSET on every side) so the letter
    images rotate exactly around their glyph centre in vmcreate.script.
    """
    canvas = Image.new("L", full, 0)
    canvas.paste(mask, pos)
    fill = fill.resize((width_px, ROWS * BLOCK))
    fill = ImageChops.multiply(fill, Image.merge("RGB", [scanlines(Image.new("L", fill.size, 255))] * 3))

    # Glow: blurred mask in the accent colour, low alpha.
    glow_alpha = canvas.filter(ImageFilter.GaussianBlur(GLOW_RADIUS)).point(lambda v: v * 45 // 100)
    out = Image.new("RGBA", full, (0, 0, 0, 0))
    out.paste(Image.new("RGBA", full, p["glow"] + (255,)), (0, 0), glow_alpha)

    # Drop shadow: the same mask offset down-right, solid.
    shadow_mask = Image.new("L", full, 0)
    shadow_mask.paste(mask, (pos[0] + SHADOW_OFFSET, pos[1] + SHADOW_OFFSET))
    out.paste(Image.new("RGBA", full, p["shadow"] + (255,)), (0, 0), shadow_mask)

    # Glyph on top.
    fill_canvas = Image.new("RGBA", full, (0, 0, 0, 0))
    fill_canvas.paste(fill.convert("RGBA"), pos)
    out.paste(fill_canvas, (0, 0), canvas)
    return out


def render_wordmark(p):
    vm = word_mask("VM")
    cr = word_mask("CREATE")
    gap = WORD_GAP * BLOCK
    w = vm.width + gap + cr.width
    h = ROWS * BLOCK

    mask = Image.new("L", (w, h), 0)
    mask.paste(vm, (0, 0))
    mask.paste(cr, (vm.width + gap, 0))

    fill = Image.new("RGB", (w, h))
    fill.paste(vertical_gradient((vm.width, h), *p["vm"]), (0, 0))
    fill.paste(vertical_gradient((cr.width, h), *p["cr"]), (vm.width + gap, 0))
    return render_glyph(mask, w, fill, p, (PAD, PAD),
                        (w + 2 * PAD + SHADOW_OFFSET, h + 2 * PAD + SHADOW_OFFSET))


LETTER_PAD = PAD + SHADOW_OFFSET  # symmetric margins; mirrors vmcreate.script


def render_letter(c, p):
    mask = word_mask(c)
    full = (mask.width + 2 * LETTER_PAD, ROWS * BLOCK + 2 * LETTER_PAD)
    fill = vertical_gradient(mask.size, *p["vm" if c in "VM" else "cr"])
    return render_glyph(mask, mask.width, fill, p, (LETTER_PAD, LETTER_PAD), full)


def render_progress(p):
    width, height = 360, 4
    track = Image.new("RGBA", (width, height), p["track"] + (255,))
    bar = horizontal_gradient((width, height), *p["bar"]).convert("RGBA")
    return track, bar


def render_cursor(p):
    return Image.new("RGBA", (9, 18), p["cursor"] + (255,))


def render_preview(wordmark, track, bar, cursor, size=(1024, 768)):
    """Approximate the running theme (layout mirrors vmcreate.script)."""
    p = PALETTES["blue"]
    w, h = size
    img = vertical_gradient(size, p["bg_top"], p["bg_bottom"]).convert("RGBA")
    wx = (w - wordmark.width) // 2
    wy = int(h * 0.42) - wordmark.height // 2
    img.alpha_composite(wordmark, (wx, wy))
    tx = (w - track.width) // 2
    ty = wy + wordmark.height - PAD + 40
    img.alpha_composite(track, (tx, ty))
    seg = bar.crop((120, 0, 216, bar.height))
    img.alpha_composite(seg, (tx + 120, ty))
    d = ImageDraw.Draw(img)
    try:
        font = ImageFont.truetype("Ubuntu-R.ttf", 18)
        small = ImageFont.truetype("UbuntuMono-R.ttf", 14)
    except OSError:
        font = small = ImageFont.load_default()
    msg = "Cloning disk 1 of 2"
    mw = d.textlength(msg, font=font)
    my = ty + 28
    d.text(((w - mw) / 2, my), msg, font=font, fill=p["message"])
    img.alpha_composite(cursor, (int((w + mw) / 2) + 6, my + 2))
    ver = "vmcreate-iso 2.0.0"
    vw = d.textlength(ver, font=small)
    d.text((w - vw - 16, h - 30), ver, font=small, fill=p["version"])
    return img


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", action="store_true", help="also write splash/preview.png")
    args = ap.parse_args()

    os.makedirs(OUT, exist_ok=True)
    for name, p in PALETTES.items():
        suffix = p["suffix"]
        wordmark = render_wordmark(p)
        track, bar = render_progress(p)
        cursor = render_cursor(p)
        wordmark.save(os.path.join(OUT, f"wordmark{suffix}.png"), optimize=True)
        track.save(os.path.join(OUT, f"track{suffix}.png"), optimize=True)
        bar.save(os.path.join(OUT, f"bar{suffix}.png"), optimize=True)
        cursor.save(os.path.join(OUT, f"cursor{suffix}.png"), optimize=True)
        letters = os.path.join(OUT, p["letters_dir"])
        os.makedirs(letters, exist_ok=True)
        for c in "VMCREATE":
            render_letter(c, p).save(os.path.join(letters, f"{c.lower()}.png"), optimize=True)
        if name == "blue" and args.preview:
            render_preview(wordmark, track, bar, cursor).save(
                os.path.join(HERE, "preview.png"), optimize=True)


if __name__ == "__main__":
    main()
